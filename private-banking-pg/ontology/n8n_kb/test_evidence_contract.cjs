function evaluate(name,productCode,domain,metricCode,data=read(`evidence_live_${name}.json`)){
 const request={question:'查詢所選產品',domains:[domain],metricCodes:[metricCode]};
 const catalog=run(code('Concept Catalog'),data.concept,{'KB Input':request});
 const paths=run(code('Concept Paths'),catalog);
 const prepared=run(code('Jev - Prepare Objects'),paths);
 const selectedConceptPaths=paths.pathCandidates.filter(p=>p.productCode===productCode && p.domain===domain);
 const decision={status:'selected',pathStatus:'confirmed',selectedConceptPaths,selections:[{productCode,domain}],candidateScores:prepared.candidates.map(c=>({...c,probability:c.productCode===productCode?0.9:0.05})),decision:{fixture:true},message:'已選取產品。'};
 return run(code('KB Result'),data.mapping,{'Concept Catalog':catalog,'Jev - Evaluate Objects':decision});
}
