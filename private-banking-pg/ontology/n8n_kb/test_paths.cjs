const fs=require('node:fs'),assert=require('node:assert/strict');
const w=JSON.parse(fs.readFileSync(__dirname+'/PB_AUM_Income_KB.evidence.ready.json','utf8'));
const m=JSON.parse(fs.readFileSync(__dirname+'/main.evidence.ready.json','utf8'));
const run=(name,input,prior={})=>new Function('$input','$',w.nodes.find(n=>n.name===name).parameters.jsCode)({first:()=>({json:input})},n=>({first:()=>({json:prior[n]})}))[0].json;
const live=JSON.parse(fs.readFileSync(__dirname+'/evidence_live_deposit_aum.json','utf8'));
const catalog=run('Concept Catalog',live.concept,{'KB Input':{question:'全體客戶月底存款AUM',domains:['aum'],metricCodes:['aum_deposit_month_end']}});
// Same object, two full branches with different scope. No technical graph at decision time.
const branch=structuredClone(catalog.products[0].conceptEvidence.aumPaths[0]);branch.relationships[0].properties.scope="TYP='存款' AND COMP='境外'";
catalog.products[0].conceptEvidence.aumPaths.push(branch);
const paths=run('Concept Paths',catalog),prep=run('Jev - Prepare Objects',paths);
let checks=0;const check=f=>{f();checks++;};
check(()=>assert.equal(paths.pathCandidates.length,2));
check(()=>assert.notEqual(paths.pathCandidates[0].pathKey,paths.pathCandidates[1].pathKey));
check(()=>assert.equal(prep.decisionRequest.state.businessPaths.length,2));
check(()=>assert(!/aumStages|incomeStages|SqlTable|sqlEvidence/.test(JSON.stringify(prep.decisionRequest.state))));
const answer=(choice,labels)=>({type:'choice',choice,probabilities:Object.fromEntries(labels.map(x=>[x,x===choice?1:0])),confidence:1});
const objectLabels=['included','uncertain','excluded'];
const body={model:'typesafe/jev-1.13-20260917',answers:{scope:answer('clear',['clear','ambiguous','none'])}};
for(const c of prep.candidates)body.answers[c.objectKey]=answer('included',objectLabels);
for(const [i,p] of paths.pathCandidates.entries())body.answers[`path::${p.pathKey}`]=answer(i===0?'included':'excluded',objectLabels);
const evaluate=b=>run('Jev - Evaluate Objects',b,{'Jev - Prepare Objects':prep});
const selected=evaluate(body);
check(()=>assert.equal(selected.status,'selected'));
check(()=>assert.equal(selected.selectedConceptPaths.length,1));
check(()=>assert.equal(selected.pathScores.length,2));
check(()=>assert.equal(selected.candidateScores[0].probability,1));
const bound=run('Selected Paths',selected,{'Concept Paths':paths});
check(()=>assert.deepEqual(bound.selectedPaths.map(p=>p.pathKey),[paths.pathCandidates[0].pathKey]));
const uncertain=structuredClone(body);uncertain.answers[`path::${paths.pathCandidates[1].pathKey}`]=answer('uncertain',objectLabels);
const blocked=evaluate(uncertain);
check(()=>assert.equal(blocked.status,'needs_clarification'));
check(()=>assert.deepEqual(blocked.selectedConceptPaths,[]));
check(()=>assert.throws(()=>run('Selected Paths',blocked,{'Concept Paths':paths})));
const rejected=structuredClone(body);for(const p of paths.pathCandidates)rejected.answers[`path::${p.pathKey}`]=answer('excluded',objectLabels);
check(()=>assert.equal(evaluate(rejected).status,'needs_clarification'));
const conflict=structuredClone(body);conflict.answers[prep.candidates[0].objectKey]=answer('excluded',objectLabels);
check(()=>assert.equal(evaluate(conflict).status,'needs_clarification'));
check(()=>assert.equal(evaluate(conflict).routeIssues[0].code,'object_path_disagreement'));
check(()=>assert.deepEqual(evaluate(conflict).selectedConceptPaths,[]));
const missing=structuredClone(body);delete missing.answers[`path::${paths.pathCandidates[0].pathKey}`];
check(()=>assert.throws(()=>evaluate(missing)));
const tampered=structuredClone(selected);tampered.selectedConceptPaths[0].nodeKeys.reverse();
check(()=>assert.throws(()=>run('Selected Paths',tampered,{'Concept Paths':paths})));
const noMapping=run('KB Result',blocked,{'Concept Catalog':catalog,'Jev - Evaluate Objects':blocked});
check(()=>assert.equal(noMapping.canGenerateSql,false));
check(()=>assert.deepEqual(noMapping.products,[]));
check(()=>assert.deepEqual(noMapping.pathScores,blocked.pathScores));
check(()=>assert.equal(w.connections['Jev - Evaluate Objects'].main[0][0].node,'Concept Route Ready'));
check(()=>assert.equal(w.connections['Concept Route Ready'].main[1][0].node,'KB Result'));
check(()=>assert.equal(m.connections['metric router'].main[0][0].node,'Product Concept KB'));
check(()=>assert.equal(m.connections['Product Concept KB'].main[0][0].node,'KB Route and Evidence Ready'));
check(()=>assert.equal(m.connections['KB Route and Evidence Ready'].main[1][0].node,'KB Not Ready'));
check(()=>assert.equal(m.connections['Available Source Metadata'].main[0][0].node,'SQL Reasoning Agent'));
fs.writeFileSync(__dirname+'/path_contract_validation.json',JSON.stringify({checksPassed:checks,syntheticDecisionFixtures:true,scenarios:['same object distinct full paths','ambiguous path blocks mapping','excluded paths block mapping','missing native answer fails','tampered path fails','main physical metadata after route gate']},null,2));
console.log(JSON.stringify({checksPassed:checks}));
