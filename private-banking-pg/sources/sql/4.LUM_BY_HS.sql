DROP TABLE 私銀客戶 PURGE;
CREATE TABLE 私銀客戶 AS
WITH 私銀AO AS (
    SELECT A.YYYYMM, AO_ID, A.PRFT_CNTR_CD, EMP_NO, SHT_NM, E.* FROM (
      SELECT * FROM DSORG.AO_INFO_HS@anadbp01_dwdbp01
      WHERE AO_TYP != 'AO1P' AND PRFT_CNTR_CD NOT IN ('2E4300', '2E5000') AND YYYYMM >= '202312'
    ) A INNER JOIN (
      --AO部門別
      SELECT * FROM DSORG.PRFT_CNTR_CD@anadbp01_dwdbp01
      WHERE BU = '私人銀行處'
    ) B ON A.PRFT_CNTR_CD = B.PRFT_CNTR_CD
    INNER JOIN (
      --在職
      SELECT * FROM DSORG.HR_EMP_HS@anadbp01_dwdbp01
      WHERE JOB_STATUS = '1' AND YYYYMM >= '202312'
    ) C ON A.EMP_NO = TRIM(C.EMP_ID) AND A.YYYYMM = C.YYYYMM
    INNER JOIN (
      --職稱
      SELECT * FROM DSORG.HR_JOB_TYP_CD@anadbp01_dwdbp01
    ) E ON C.COMP_SERIAL_NO = E.COMP_SERIAL_NO AND C.PST_CD = E.PST_CD
    WHERE PST_NM LIKE '%CA%' OR EMP_NO = '840087'
)
SELECT A.YYYYMM, CUST_ID, PRFT_CNTR_CD FROM (
  SELECT DISTINCT YYYYMM, CUST_ID, AO_ID FROM DSCIF.AO_CUST_REL_HS@anadbp01_dwdbp01
  WHERE YYYYMM >= '202312'
) A INNER JOIN (
  SELECT * FROM 私銀AO
) B ON A.AO_ID = B.AO_ID AND A.YYYYMM = B.YYYYMM
;

DROP TABLE 台幣放款_私銀 PURGE;

CREATE TABLE 台幣放款_私銀 AS 
SELECT YYYYMM
, 'TW' AREA
, CUST_ID
, ACCT_NO
, ACC_CD
, APP_AMT
, LN_BAL
, PRFT_CNTR_CD
, ACC_SUB_CD
FROM DSLON.LN_NT_ACCT_HS@anadbp01_dwdbp01
WHERE PRFT_CNTR_CD like '2E%' AND YYYYMM >= '202312'
AND LN_BAL != 0 
;

DROP TABLE 外幣放款_私銀 PURGE;
CREATE TABLE 外幣放款_私銀 AS 
SELECT YYYYMM
  , 'TW' AREA --國內外幣
  , CUST_ID
  , TXN_NO
  , ACC_CD
  , BAL_AMT
  , CURR_TYP
  , PRFT_CNTR_CD
  , ACC_SUB_CD
FROM DSLON.LN_FN_ACCT_HS@anadbp01_dwdbp01
WHERE PRFT_CNTR_CD LIKE '2E%' AND YYYYMM >= '202312'
AND BAL_AMT != 0 
;
DROP　TABLE 動用率_私銀;
CREATE TABLE 動用率_私銀 AS 
SELECT DISTINCT  'TW' AREA, A.FACILITY_NO, ID_NO --國內額度
, A.FAC_APPV_AMOUNT_TWD, A.FAC_APPV_CURRENCY
FROM ( 
  SELECT * FROM DSWBS.V_FAC_NODE@anadbp01_dwdbp01
  WHERE NODE_PATH = '0' AND FAC_STATUS = '05' 
) A INNER JOIN (
  SELECT * FROM DSWBS.WBS_ACTL@anadbp01_dwdbp01
) B ON A.FACILITY_NO = B.FACILITY_NO 
LEFT JOIN (
  SELECT * FROM DSWBS.V_FAC_MAIN@anadbp01_dwdbp01
) D ON A.FAC_MAIN_SEQ = D.FAC_MAIN_SEQ 
WHERE A.FAC_APPV_AMOUNT_TWD IS NOT NULL
;

